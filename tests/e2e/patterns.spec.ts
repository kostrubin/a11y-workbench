import { expect, test } from "@playwright/test";

test("forms: errors are associated, focus recovers, values survive and success stays local", async ({ page }) => {
  const submissions: string[] = [];
  page.on("request", (request) => { if (!["GET", "HEAD"].includes(request.method())) submissions.push(request.method()); });
  await page.goto("/patterns/forms/");
  const surface = page.locator("[data-pattern='forms']");
  await expect(surface).toHaveAttribute("data-state", "forms.initial");
  await expect(surface).toHaveAttribute("data-variant", "corrected");
  await page.getByRole("button", { name: "Save local example" }).focus();
  await page.keyboard.press("Enter");
  await expect(surface).toHaveAttribute("data-state", "forms.invalid");
  const summary = page.getByRole("alert");
  await expect(summary).toBeFocused();
  await expect(summary).toContainText("Enter a display name.");
  await expect(page.getByLabel("Display name", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await summary.getByRole("link", { name: "Enter an email address", exact: false }).click();
  await expect(page.getByLabel("Email", { exact: true })).toBeFocused();
  await expect(page.getByLabel("Email", { exact: true })).toHaveAttribute("aria-describedby", "demo-email-hint demo-email-error");
  await page.getByLabel("Display name", { exact: true }).fill("Synthetic Reviewer");
  await page.getByLabel("Email", { exact: true }).fill("invalid");
  await page.getByRole("button", { name: "Save local example" }).click();
  await expect(page.getByLabel("Display name", { exact: true })).toHaveValue("Synthetic Reviewer");
  await expect(page.getByLabel("Email", { exact: true })).toHaveValue("invalid");
  await page.getByLabel("Email", { exact: true }).fill("reviewer@example.test");
  await page.getByRole("button", { name: "Save local example" }).focus();
  await page.keyboard.press("Enter");
  await expect(surface).toHaveAttribute("data-state", "forms.success");
  await expect(surface).toContainText("Example saved locally. No data was submitted to a server.");
  expect(submissions).toEqual([]);
  await page.reload();
  await expect(page.getByLabel("Display name", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Email", { exact: true })).toHaveValue("");
});

test("dialog: initial focus, modal containment, Escape, saving and focus return", async ({ page }) => {
  await page.goto("/patterns/dialog/");
  const surface = page.locator("[data-pattern='dialog']");
  const opener = page.getByRole("button", { name: "Edit display name", exact: true });
  await expect(surface).toHaveAttribute("data-state", "dialog.closed");
  await opener.focus();
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog", { name: "Edit display name" });
  await expect(dialog).toBeVisible();
  await expect(surface).toHaveAttribute("data-state", "dialog.open");
  await expect(dialog.getByLabel("Display name", { exact: true })).toBeFocused();
  for (const key of ["Tab", "Tab", "Tab", "Shift+Tab", "Shift+Tab", "Shift+Tab"]) {
    await page.keyboard.press(key);
    expect(await page.evaluate(() => Boolean(document.activeElement?.closest("#example-dialog")))).toBe(true);
  }
  await page.evaluate(() => (document.querySelector("[data-action='dialog.open']") as HTMLButtonElement).focus());
  expect(await page.evaluate(() => Boolean(document.activeElement?.closest("#example-dialog")))).toBe(true);
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(surface).toHaveAttribute("data-state", "dialog.closed");
  await expect(opener).toBeFocused();
  await page.keyboard.press("Enter");
  await dialog.getByLabel("Display name", { exact: true }).fill("Synthetic Editor");
  await dialog.getByRole("button", { name: "Save name", exact: true }).click();
  await expect(surface).toHaveAttribute("data-state", "dialog.saved");
  await expect(surface).toContainText("Synthetic Editor");
  await expect(opener).toBeFocused();
  await page.keyboard.press("Enter");
  await dialog.getByLabel("Display name", { exact: true }).fill("Discarded Synthetic Draft");
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(surface).toContainText("Synthetic Editor");
  await expect(surface).not.toContainText("Discarded Synthetic Draft");
  await expect(opener).toBeFocused();
});

test("menu: Enter and Space open, arrows and endpoints navigate, activation and Escape return focus", async ({ page }) => {
  await page.goto("/patterns/menu-button/");
  const surface = page.locator("[data-pattern='menu']");
  const button = page.getByRole("button", { name: "Choose display view" });
  await expect(surface).toHaveAttribute("data-state", "menu.closed");
  await button.focus();
  await page.keyboard.press("Enter");
  await expect(button).toHaveAttribute("aria-expanded", "true");
  await expect(page.getByRole("menuitem", { name: "Compact", exact: true })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "Comfortable", exact: true })).toBeFocused();
  await page.keyboard.press("End");
  await expect(page.getByRole("menuitem", { name: "Detailed", exact: true })).toBeFocused();
  await page.keyboard.press("Home");
  await expect(page.getByRole("menuitem", { name: "Compact", exact: true })).toBeFocused();
  await page.keyboard.press("ArrowUp");
  await expect(page.getByRole("menuitem", { name: "Detailed", exact: true })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(surface).toHaveAttribute("data-state", "menu.selected");
  await expect(page.getByRole("status")).toContainText("Selected view: Detailed");
  await expect(button).toBeFocused();
  await page.keyboard.press("Space");
  await expect(surface).toHaveAttribute("data-state", "menu.open");
  await expect(page.getByRole("menuitem", { name: "Compact", exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(button).toHaveAttribute("aria-expanded", "false");
  await expect(button).toBeFocused();
  await page.keyboard.press("ArrowUp");
  await expect(page.getByRole("menuitem", { name: "Detailed", exact: true })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(button).toHaveAttribute("aria-expanded", "false");
  expect(await page.evaluate(() => Boolean(document.activeElement?.closest("#example-action-menu")))).toBe(false);
});

test("broken variants: deliberate failures stay contained and an outside reset returns each fixture", async ({ page }) => {
  await page.goto("/patterns/forms/?variant=broken");
  await expect(page.locator("[data-pattern='forms']")).toHaveAttribute("data-variant", "broken");
  await expect(page.getByLabel("Display name", { exact: true })).toHaveCount(0);
  await page.locator("[data-action='forms.submit']").click();
  await expect(page.locator("[data-pattern='forms']")).toHaveAttribute("data-state", "forms.invalid");
  await expect(page.locator("#demo-name")).not.toHaveAttribute("aria-invalid", "true");
  await page.locator("[data-action='forms.reset']").click();
  await expect(page.locator("[data-pattern='forms']")).toHaveAttribute("data-state", "forms.initial");
  await page.getByRole("radio", { name: "Corrected", exact: true }).check();
  await expect(page.getByLabel("Display name", { exact: true })).toBeVisible();

  await page.goto("/patterns/dialog/?variant=broken");
  await expect(page.locator("[data-pattern='dialog']")).toHaveAttribute("data-variant", "broken");
  const opener = page.locator("[data-action='dialog.open']");
  await opener.click();
  await expect(opener).toBeFocused();
  await expect(page.locator("dialog[open]")).toHaveCount(0);
  await page.locator("[data-action='dialog.reset']").click();
  await expect(page.locator("[data-pattern='dialog']")).toHaveAttribute("data-state", "dialog.closed");

  await page.goto("/patterns/menu-button/?variant=broken");
  await expect(page.locator("[data-pattern='menu']")).toHaveAttribute("data-variant", "broken");
  const trigger = page.locator("[data-action='menu.open']");
  await trigger.focus();
  await page.keyboard.press("Enter");
  await expect(trigger).toBeFocused();
  await expect(trigger).not.toHaveAttribute("aria-expanded", "true");
  await page.keyboard.press("ArrowDown");
  await expect(trigger).toBeFocused();
  await page.locator("[data-action='menu.reset']").click();
  await expect(page.locator("[data-pattern='menu']")).toHaveAttribute("data-state", "menu.closed");
  await page.getByRole("radio", { name: "Corrected", exact: true }).check();
  await trigger.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("menuitem", { name: "Compact", exact: true })).toBeFocused();
});
